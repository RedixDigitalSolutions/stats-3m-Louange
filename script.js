let currentLang = "fr";
let data = null;
let sortMode = "views"; // 'views' | 'date'
const charts = {};

/* ====== INIT ====== */
document.addEventListener("DOMContentLoaded", async () => {
  const resp = await fetch("data.json");
  data = await resp.json();
  setupNavigation();
  applyTranslations();
  renderAllCharts();
  renderAllTables();
});

/* ====== NAVIGATION ====== */
function setupNavigation() {
  document.querySelectorAll(".nav-item").forEach((item) => {
    item.addEventListener("click", () => {
      const tab = item.dataset.tab;
      document
        .querySelectorAll(".nav-item")
        .forEach((n) => n.classList.remove("active"));
      item.classList.add("active");
      document
        .querySelectorAll(".tab-content")
        .forEach((t) => t.classList.remove("active"));
      document.getElementById("tab-" + tab).classList.add("active");
      // Close sidebar on mobile
      document.getElementById("sidebar").classList.remove("open");
    });
  });
}
function toggleSidebar() {
  document.getElementById("sidebar").classList.toggle("open");
}

function setSortMode(mode) {
  sortMode = mode;
  document
    .getElementById("sortViewsBtn")
    .classList.toggle("active", mode === "views");
  document
    .getElementById("sortDateBtn")
    .classList.toggle("active", mode === "date");
  renderCombinedPosts();
}

/* ====== LANGUAGE ====== */
function toggleLang() {
  currentLang = currentLang === "fr" ? "ar" : "fr";
  document.getElementById("langLabel").textContent =
    currentLang === "fr" ? "العربية" : "Français";
  document.documentElement.lang = currentLang === "ar" ? "ar" : "fr";
  document.documentElement.dir = currentLang === "ar" ? "rtl" : "ltr";
  document.body.classList.toggle("rtl", currentLang === "ar");
  applyTranslations();
  destroyAllCharts();
  renderAllCharts();
  renderAllTables();
}

function applyTranslations() {
  const t = i18n[currentLang];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (t[key]) el.textContent = t[key];
  });
}

/* ====== CHART HELPERS ====== */
const GOLD = "#c9933b";
const GOLD_LIGHT = "#e8c574";
const BLUE = "#1877f2";
const PINK = "#e1306c";
const TEAL = "#00b4d8";
const GREEN = "#10b981";
const PURPLE = "#7c3aed";
const RED = "#ef4444";
const DARK = "#1a1a1a";

function destroyAllCharts() {
  Object.values(charts).forEach((c) => c.destroy());
  Object.keys(charts).forEach((k) => delete charts[k]);
}

function t(key) {
  return i18n[currentLang][key] || key;
}

function makeLineChart(id, labels, datasets, stacked) {
  const ctx = document.getElementById(id);
  if (!ctx) return;
  charts[id] = new Chart(ctx, {
    type: "line",
    data: { labels, datasets },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      interaction: { mode: "index", intersect: false },
      plugins: { legend: { position: "top", labels: { font: { size: 12 } } } },
      scales: {
        x: {
          ticks: { maxRotation: 45, font: { size: 10 } },
          grid: { display: false },
        },
        y: {
          beginAtZero: true,
          stacked: !!stacked,
          ticks: { font: { size: 11 } },
        },
      },
    },
  });
}

function makeBarChart(id, labels, datasets, horizontal, stacked) {
  const ctx = document.getElementById(id);
  if (!ctx) return;
  charts[id] = new Chart(ctx, {
    type: "bar",
    data: { labels, datasets },
    options: {
      indexAxis: horizontal ? "y" : "x",
      responsive: true,
      maintainAspectRatio: false,
      plugins: {
        legend: {
          display: datasets.length > 1,
          position: "top",
          labels: { font: { size: 12 } },
        },
      },
      scales: {
        x: {
          stacked: !!stacked,
          ticks: { font: { size: 10 } },
          grid: { display: horizontal },
        },
        y: {
          stacked: !!stacked,
          beginAtZero: true,
          ticks: { font: { size: 10 } },
          grid: { display: !horizontal },
        },
      },
    },
  });
}

function makeDoughnutChart(id, labels, dataVals, colors) {
  const ctx = document.getElementById(id);
  if (!ctx) return;
  charts[id] = new Chart(ctx, {
    type: "doughnut",
    data: {
      labels,
      datasets: [
        {
          data: dataVals,
          backgroundColor: colors,
          borderWidth: 2,
          borderColor: "#fff",
        },
      ],
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      plugins: {
        legend: {
          position: "right",
          labels: { font: { size: 11 }, padding: 12 },
        },
      },
    },
  });
}

const palette8 = [GOLD, BLUE, GREEN, PURPLE, RED, TEAL, PINK, "#f59e0b"];

/* ====== RENDER ALL CHARTS ====== */
function renderAllCharts() {
  if (!data) return;
  renderOverviewCharts();
  renderFacebookCharts();
  renderInstagramCharts();
  renderTiktokCharts();
  renderAdsCharts();
  renderAudienceCharts();
}

/* ====== OVERVIEW CHARTS ====== */
function renderOverviewCharts() {
  // Platform Views Bar
  makeBarChart(
    "platformViewsChart",
    ["Facebook", "Instagram", "TikTok"],
    [
      {
        label: t("views_label"),
        data: [
          data.overview.facebookViews,
          data.overview.instagramViews,
          data.overview.tiktokViews,
        ],
        backgroundColor: [BLUE, PINK, DARK],
        borderRadius: 8,
        barPercentage: 0.6,
      },
    ],
  );

  // Platform Followers Doughnut (FB + IG + TikTok)
  makeDoughnutChart(
    "platformFollowersChart",
    [
      "Facebook (" + data.overview.facebookFollowers + ")",
      "Instagram (" + data.overview.instagramFollowers + ")",
      "TikTok (" + data.overview.tiktokFollowers + ")",
    ],
    [
      data.overview.facebookFollowers,
      data.overview.instagramFollowers,
      data.overview.tiktokFollowers,
    ],
    [BLUE, PINK, DARK],
  );

  // Followers over time
  makeLineChart("overviewFollowersChart", data.facebook.follows.dates, [
    {
      label: t("follows_label"),
      data: data.facebook.follows.values,
      borderColor: GOLD,
      backgroundColor: "rgba(201,147,59,0.1)",
      fill: true,
      tension: 0.4,
      pointRadius: 3,
    },
  ]);

  // Ad spend by campaign
  const camps = data.adsManager.campaigns;
  makeBarChart(
    "adSpendChart",
    camps.map((c) => (c.name.length > 22 ? c.name.slice(0, 22) + "…" : c.name)),
    [
      {
        label: t("spent_label"),
        data: camps.map((c) => c.spent),
        backgroundColor: palette8,
        borderRadius: 6,
        barPercentage: 0.7,
      },
    ],
    true,
  );

  // Cost per message comparison
  const msgCamps = camps.filter((c) => c.messagingConversations > 0);
  makeBarChart(
    "costPerMsgChart",
    msgCamps.map((c) =>
      c.name.length > 20 ? c.name.slice(0, 20) + "…" : c.name,
    ),
    [
      {
        label: t("cost_msg_label"),
        data: msgCamps.map((c) => c.costPerMessage),
        backgroundColor: msgCamps.map((_, i) => palette8[i % palette8.length]),
        borderRadius: 6,
        barPercentage: 0.65,
      },
    ],
    true,
  );
}

