function renderAllCharts() {
  if (!data) return;
  renderOverviewCharts();
  renderFacebookCharts();
  renderInstagramCharts();
  renderTiktokCharts();
  renderAdsCharts();
}

/* ====== OVERVIEW CHARTS ====== */
function renderOverviewCharts() {
  // Platform Views Bar
  makeBarChart(
    "platformViewsChart",
    ["Facebook", "Instagram", "TikTok"],
    [
      {
        label: t("views_label"),
        data: [
          data.overview.facebookViews,
          data.overview.instagramViews,
          data.overview.tiktokViews,
        ],
        backgroundColor: [BLUE, PINK, DARK],
        borderRadius: 8,
        barPercentage: 0.6,
      },
    ],
  );

  // Platform Followers Doughnut (FB + IG + TikTok)
  makeDoughnutChart(
    "platformFollowersChart",
    [
      "Facebook (" + data.overview.facebookFollowers + ")",
      "Instagram (" + data.overview.instagramFollowers + ")",
      "TikTok (" + data.overview.tiktokFollowers + ")",
    ],
    [
      data.overview.facebookFollowers,
      data.overview.instagramFollowers,
      data.overview.tiktokFollowers,
    ],
    [BLUE, PINK, DARK],
  );

  // Followers over time
  makeLineChart("overviewFollowersChart", data.facebook.follows.dates, [
    {
      label: t("follows_label"),
      data: data.facebook.follows.values,
      borderColor: GOLD,
      backgroundColor: "rgba(201,147,59,0.1)",
      fill: true,
      tension: 0.4,
      pointRadius: 3,
    },
  ]);

  // Ad spend by campaign
  const camps = data.adsManager.campaigns;
  makeBarChart(
    "adSpendChart",
    camps.map((c) => (c.name.length > 22 ? c.name.slice(0, 22) + "…" : c.name)),
    [
      {
        label: t("spent_label"),
        data: camps.map((c) => c.spent),
        backgroundColor: palette8,
        borderRadius: 6,
        barPercentage: 0.7,
      },
    ],
    true,
  );

  // Cost per message comparison
  const msgCamps = camps.filter((c) => c.messagingConversations > 0);
  makeBarChart(
    "costPerMsgChart",
    msgCamps.map((c) =>
      c.name.length > 20 ? c.name.slice(0, 20) + "…" : c.name,
    ),
    [
      {
        label: t("cost_msg_label"),
        data: msgCamps.map((c) => c.costPerMessage),
        backgroundColor: msgCamps.map((_, i) => palette8[i % palette8.length]),
        borderRadius: 6,
        barPercentage: 0.65,
      },
    ],
    true,
  );
}

