/* ====== UTILITIES ====== */
function num(n) {
  return (n || 0).toLocaleString();
}
function escapeHtml(s) {
  const div = document.createElement("div");
  div.appendChild(document.createTextNode(s || ""));
  return div.innerHTML;
}
function escapeAttr(s) {
  return (s || "")
    .replace(/&/g, "&amp;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}
function getBadge(type) {
  const t = (type || "").toLowerCase();
  if (t.includes("reel")) return '<span class="badge badge-reel">Reel</span>';
  if (t.includes("video") || t.includes("live"))
    return '<span class="badge badge-video">Video</span>';
  if (t.includes("link")) return '<span class="badge badge-link">Link</span>';
  if (t.includes("photo") || t.includes("image") || t.includes("carousel"))
    return '<span class="badge badge-photo">Photo</span>';
  return '<span class="badge badge-inactive">' + escapeHtml(type) + "</span>";
}
