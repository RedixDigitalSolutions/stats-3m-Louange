const DARK = "#1a1a1a";

function destroyAllCharts() {
  Object.values(charts).forEach((c) => c.destroy());
  Object.keys(charts).forEach((k) => delete charts[k]);
}

function t(key) {
  return i18n[currentLang][key] || key;
}

function makeLineChart(id, labels, datasets, stacked) {
  const ctx = document.getElementById(id);
  if (!ctx) return;
  charts[id] = new Chart(ctx, {
    type: "line",
    data: { labels, datasets },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      interaction: { mode: "index", intersect: false },
      plugins: { legend: { position: "top", labels: { font: { size: 12 } } } },
      scales: {
        x: {
          ticks: { maxRotation: 45, font: { size: 10 } },
          grid: { display: false },
        },
        y: {
          beginAtZero: true,
          stacked: !!stacked,
          ticks: { font: { size: 11 } },
        },
      },
    },
  });
}

function makeBarChart(id, labels, datasets, horizontal, stacked) {
  const ctx = document.getElementById(id);
  if (!ctx) return;
  charts[id] = new Chart(ctx, {
    type: "bar",
    data: { labels, datasets },
    options: {
      indexAxis: horizontal ? "y" : "x",
      responsive: true,
      maintainAspectRatio: false,
      plugins: {
        legend: {
          display: datasets.length > 1,
          position: "top",
          labels: { font: { size: 12 } },
        },
      },
      scales: {
        x: {
          stacked: !!stacked,
          ticks: { font: { size: 10 } },
          grid: { display: horizontal },
        },
        y: {
          stacked: !!stacked,
          beginAtZero: true,
          ticks: { font: { size: 10 } },
          grid: { display: !horizontal },
        },
      },
    },
  });
}

function makeDoughnutChart(id, labels, dataVals, colors) {
  const ctx = document.getElementById(id);
  if (!ctx) return;
  charts[id] = new Chart(ctx, {
    type: "doughnut",
    data: {
      labels,
      datasets: [
        {
          data: dataVals,
          backgroundColor: colors,
          borderWidth: 2,
          borderColor: "#fff",
        },
      ],
    },
    options: {
      responsive: true,
      maintainAspectRatio: false,
      plugins: {
        legend: {
          position: "right",
          labels: { font: { size: 11 }, padding: 12 },
        },
      },
    },
  });
}

const palette8 = [GOLD, BLUE, GREEN, PURPLE, RED, TEAL, PINK, "#f59e0b"];

